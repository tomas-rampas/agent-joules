using AgentJoules.Cli;
using AgentJoules.Core.Runs;
using AgentJoules.TestSupport;

using Xunit.Sdk;

namespace AgentJoules.Specs.Support;

/// <summary>
/// The state of one AJ-131 scenario (the README guides, REQ-025 and REQ-032), handed to the step class by Reqnroll context injection. The texts are in memory and the committed files are only read. The help of a
/// command is the real command line run in process through <see cref="CliHarness"/>; the screenshot link rule is modelled in a <see cref="TempWorkspace"/> that holds fixture run files, a copy of the README with the
/// result markers and, when the scenario says so, the screenshot file, so no file of the repository is created or deleted.
/// </summary>
public sealed class ReadmeGuidesContext : IDisposable
{
    private TempWorkspace? _workspace;

    /// <summary>The README text under test, possibly a mutated copy of the committed one.</summary>
    public string Readme { get; set; } = string.Empty;

    /// <summary>The failures of the last check.</summary>
    public IReadOnlyList<string> Failures { get; set; } = [];

    /// <summary>The lines of the section extracted by the When step.</summary>
    public IReadOnlyList<string> Section { get; set; } = [];

    /// <summary>The rows of the exit-code table found by the When step.</summary>
    public IReadOnlyList<ExitCodeRow> Rows { get; set; } = [];

    /// <summary>The help runs of the scenario by command name.</summary>
    public Dictionary<string, CliRunResult> Help { get; } = [];

    /// <summary>The README of the workspace after <see cref="UpdateWorkspaceReadmeAsync"/>, or the README text of the scenario before it.</summary>
    public string WorkspaceReadme { get; private set; } = string.Empty;

    /// <summary>Whether the workspace holds <c>docs/report/dashboard.png</c>.</summary>
    public bool ScreenshotExists { get; private set; }

    /// <summary>Whether the When step regenerates the README block in the workspace before the link rule is applied.</summary>
    public bool Regenerate { get; private set; }

    private TempWorkspace Workspace => _workspace ??= TempWorkspace.CreateEmpty();

    /// <summary>Lays out the workspace of a link scenario: the three fixture run files and the README, plus the screenshot when asked.</summary>
    /// <param name="readme">The README text; the result markers are added when it has none.</param>
    /// <param name="screenshotExists">Whether the screenshot file exists in the workspace.</param>
    /// <param name="regenerate">Whether the README block is regenerated by <c>report --update-readme</c> before the check.</param>
    public void PrepareWorkspace(string readme, bool screenshotExists, bool regenerate)
    {
        ReadmeFixtures.AddCommitted(Workspace, Tier.Local, Tier.Nvidia, Tier.Nebius);
        WorkspaceReadme = ReadmeFixtures.WithMarkers(readme);
        _ = Workspace.WriteFile("README.md", WorkspaceReadme);
        if (screenshotExists)
        {
            _ = Workspace.WriteFile(DocumentChecks.DashboardScreenshot, "png");
        }

        ScreenshotExists = screenshotExists;
        Regenerate = regenerate;
    }

    /// <summary>Runs <c>report --update-readme</c> in the workspace and reads the README back.</summary>
    /// <returns>A task that completes with the result of the command.</returns>
    public async Task<CliRunResult> UpdateWorkspaceReadmeAsync()
    {
        CliRunResult result = await CliHarness.RunTokensAsync(["report", "--update-readme"], new CliHostOverrides(WorkingDirectory: Workspace.Root));
        WorkspaceReadme = File.ReadAllText(Path.Combine(Workspace.Root, "README.md"));

        return result;
    }

    /// <summary>Whether the screenshot file exists in the workspace, asked of the file system.</summary>
    /// <returns>True when the file exists.</returns>
    public bool ScreenshotOnDisk() => File.Exists(Path.Combine(Workspace.Root, DocumentChecks.DashboardScreenshot));

    /// <summary>Runs <c>AJ &lt;command&gt; --help</c> in process and keeps the result.</summary>
    /// <param name="command">The command name.</param>
    /// <returns>A task that completes with the result.</returns>
    public async Task<CliRunResult> RunHelpAsync(string command)
    {
        CliRunResult result = await CliHarness.RunTokensAsync([command, "--help"]);
        Help[command] = result;

        return result;
    }

    /// <summary>The text of standard output and standard error of the help run of a command.</summary>
    /// <param name="command">The command name.</param>
    /// <returns>The text.</returns>
    /// <exception cref="XunitException">The help of the command has not run.</exception>
    public string HelpText(string command) =>
        Help.TryGetValue(command, out CliRunResult? result) ? result.Stdout + "\n" + result.Stderr : throw new XunitException($"The help of {command} has not run yet.");

    /// <inheritdoc />
    public void Dispose() => _workspace?.Dispose();
}